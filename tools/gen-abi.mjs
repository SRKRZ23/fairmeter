// Writes packages/fairmeter/src/abi.ts from the Foundry build output, so the SDK ABI never drifts from the contract.
import { readFileSync, writeFileSync } from "node:fs";
const art = JSON.parse(readFileSync(new URL("../contracts/out/FairMeter.sol/FairMeter.json", import.meta.url)));
const out = `// Generated by tools/gen-abi.mjs from contracts/src/FairMeter.sol. Do not edit by hand.
export const fairMeterAbi = ${JSON.stringify(art.abi, null, 2)} as const;
`;
writeFileSync(new URL("../packages/fairmeter/src/abi.ts", import.meta.url), out);
console.log(`abi.ts: ${art.abi.length} entries`);
